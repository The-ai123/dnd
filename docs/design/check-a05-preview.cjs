const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');

(async () => {
  const fragment = fs.readFileSync(path.join(__dirname, 'a05-interface-review.html'), 'utf8');
  const outputDirectory = path.resolve(__dirname, '../../test-results/a05-review');
  fs.mkdirSync(outputDirectory, { recursive: true });
  assert(!fragment.includes('\\"'), 'Escaped HTML quotes');
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1024, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setContent('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><style>body{margin:0;padding:12px;background:transparent}</style></head><body><script>window.openai={widgetState:{modelContent:{reviewRevision:3,page:"play",player:false}}};</script>' + fragment + '</body></html>');
  const root = page.locator('#a05-review');
  const nav = root.locator('.workspace');
  await root.locator('[data-creature="Mira"]').click();
  assert((await root.locator('#active-name').textContent()).startsWith('Torren'));
  assert.equal(await root.locator('#inspector-header-hp').textContent(), 'HP 18 / 24');
  assert.equal(await root.locator('#active-header-hp').textContent(), 'HP 30 / 30');
  await root.locator('#detail').click();
  assert(await root.locator('#story-map').evaluate(el => el.classList.contains('low-detail')));
  await root.locator('#detail').click();
  await root.locator('#new-map').click();
  assert(await root.locator('#staging').isVisible());
  await root.locator('#cancel-map').click();
  assert(!(await root.locator('#staging').isVisible()));
  const dock = root.locator('.inspector-dock');
  const dockBefore = await dock.boundingBox();
  const upper = await root.locator('.play-grid').boundingBox();
  assert(dockBefore.y >= upper.y + upper.height - 1, 'Dock must sit below the upper workspace');
  const fixedActiveHeader = await root.locator('.active-heading').boundingBox();
  await root.locator('.sheet-content').evaluate(el => { el.scrollTop = 200; });
  assert.equal((await dock.boundingBox()).y, dockBefore.y, 'Sheet scrolling must not move dock');
  assert.equal((await root.locator('.active-heading').boundingBox()).y, fixedActiveHeader.y, 'Active header must stay fixed');
  await root.locator('.sheet-content').evaluate(el => { el.scrollTop = 0; });
  assert(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight), 'Desktop Play should fit without page scrolling');
  await root.getByRole('button', { name: 'Effects', exact: true }).click();
  assert(await root.locator('[data-inspector-page="Effects"]').isVisible());
  await root.getByRole('button', { name: 'Stats', exact: true }).click();
  await root.locator('.dock-resizer').focus();
  await root.locator('.dock-resizer').press('ArrowUp');
  assert.equal(Math.round((await dock.boundingBox()).height), 240);
  assert.equal(Math.round((await dock.boundingBox()).y+(await dock.boundingBox()).height), Math.round(dockBefore.y+dockBefore.height));
  await root.locator('.dock-resizer').press('ArrowDown');
  await root.locator('#pin').click();
  await root.locator('[data-creature="Guard"]').click();
  assert.equal(await root.locator('#inspector-records button').count(), 2);
  await root.locator('[data-inspector-record="Mira"]').click();
  await root.getByRole('button', { name: 'Inventory', exact: true }).click();
  assert(await root.locator('#inspector-fields').evaluate(el => el.scrollHeight > el.clientHeight));
  const dockHeaderPosition = await root.locator('.inspector-top').boundingBox();
  await root.locator('#inspector-fields').evaluate(el => { el.scrollTop = 220; });
  assert.equal((await root.locator('.inspector-top').boundingBox()).y, dockHeaderPosition.y);
  assert.equal((await dock.boundingBox()).y, dockBefore.y);
  await root.getByRole('button', { name: 'Stats', exact: true }).click();
  await page.screenshot({ path: path.join(outputDirectory, 'a05-play-light.png'), fullPage: true });
  await nav.getByRole('button', { name: 'Mira · Entity' }).click();
  await root.locator('#hp-input').fill('-');
  await page.waitForTimeout(600);
  assert.equal(await root.locator('#editor-save').textContent(), 'Editing · Not saved');
  assert.equal(await root.locator('#hp-valid').textContent(), 'Validated gameplay HP: 18 / 24');
  await root.locator('#hp-input').press('Enter');
  assert.equal(await root.locator('#hp-valid').textContent(), 'Validated gameplay HP: 18 / 24');
  assert.equal(await root.locator('#editor-save').textContent(), 'Draft saved · Fix highlighted fields');
  await root.locator('#save-failure').check();
  await root.locator('#hp-input').fill('12');
  await page.waitForTimeout(450);
  assert.equal(await root.locator('#editor-save').textContent(), 'Editing · Not saved');
  await root.locator('#hp-input').press('Tab');
  assert.equal(await root.locator('#hp-valid').textContent(), 'Validated gameplay HP: 18 / 24');
  assert.equal(await root.locator('#editor-save').textContent(), 'Not saved · Retry');
  await root.locator('#retry-save').click();
  assert.equal(await root.locator('#hp-valid').textContent(), 'Validated gameplay HP: 12 / 24');
  assert.equal(await root.locator('#sheet-header-hp').textContent(), 'HP 12 / 24');
  assert.equal(await root.locator('#inspector-header-hp').textContent(), 'HP 12 / 24');
  await root.locator('#hp-input').fill('-');
  await root.locator('#hp-input').press('Enter');
  await page.screenshot({ path: path.join(outputDirectory, 'a05-editor-invalid.png'), fullPage: true });
  const note = root.locator('#notes-input');
  await note.fill('Courier found');
  await note.press('End');
  await note.press('Enter');
  assert.equal(await note.inputValue(), 'Courier found\n');
  await page.waitForTimeout(500);
  assert.equal(await root.locator('#notes-status').textContent(), 'Editing · Not saved');
  await note.press('Control+Enter');
  assert.equal(await root.locator('#notes-status').textContent(), 'Saved');
  assert.equal(await note.inputValue(), 'Courier found\n');
  await note.fill('Second note edit');
  await note.press('Tab');
  assert.equal(await root.locator('#notes-status').textContent(), 'Saved');
  await nav.getByRole('button', { name: 'World Manager', exact: true }).click();
  await root.locator('#record-search').fill('Edda');
  assert.equal(await root.locator('#manager-rows tr').count(), 1);
  await root.getByRole('button', { name: 'Edda', exact: true }).click();
  assert((await root.locator('#reservation-message').textContent()).startsWith('Unreserved'));
  await root.locator('#record-search').fill('');
  await nav.getByRole('button', { name: 'Settings', exact: true }).click();
  await root.locator('#appearance').selectOption('dark');
  await root.locator('#density').selectOption('Dense');
  await nav.getByRole('button', { name: 'Play', exact: true }).click();
  await page.screenshot({ path: path.join(outputDirectory, 'a05-play-dark-dense.png'), fullPage: true });
  await root.locator('#window-player').click();
  assert(await root.locator('#public-window').isVisible());
  assert(!(await root.locator('#story-window').isVisible()));
  assert(!/4 \/ 16|AC 13|Private/.test(await root.locator('#public-window').textContent()));
  assert(!/Guard|GU/.test(await root.locator('#public-window').textContent()));
  assert.equal(await root.locator('.public-map .guard .creature-name').textContent(), 'unknown');
  assert(await root.locator('#player-queue-cards').evaluate(el => el.scrollWidth > el.clientWidth));
  await root.locator('#player-queue-cards').evaluate(el => { el.scrollLeft = 180; });
  assert(await root.locator('#player-queue-cards').evaluate(el => el.scrollLeft > 0));
  await root.locator('#player-queue-cards').evaluate(el => { el.scrollLeft = 0; });
  await page.screenshot({ path: path.join(outputDirectory, 'a05-player-queue-expanded.png'), fullPage: true });
  const expandedMap = await root.locator('.public-map').boundingBox();
  await root.locator('#collapse-public').click();
  assert(!(await root.locator('#player-queue-cards').isVisible()));
  assert(await root.locator('#collapse-public').isVisible());
  assert.equal(await root.locator('#collapse-public').getAttribute('aria-expanded'), 'false');
  assert((await root.locator('.public-map').boundingBox()).height > expandedMap.height);
  await page.screenshot({ path: path.join(outputDirectory, 'a05-player-queue-collapsed.png'), fullPage: true });
  await root.locator('#collapse-public').click();
  assert(await root.locator('#player-queue-cards').isVisible());
  for (const width of [320, 736, 1024]) {
    await page.setViewportSize({ width, height: 1080 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Public queue overflows page at ${width}`);
  }
  await page.setViewportSize({ width:1024, height:1000 });
  await root.locator('#back-story').click();
  await nav.getByRole('button', { name: 'Home', exact: true }).click();
  assert.equal(await root.locator('#home-tools button').count(), 11);
  await page.screenshot({ path: path.join(outputDirectory, 'a05-home.png'), fullPage: true });
  for (const width of [320, 736, 1024, 1920]) {
    await page.setViewportSize({ width, height: 1080 });
    for (const screen of ['home', 'play', 'manager', 'editor', 'settings']) {
      await nav.locator('[data-open="' + screen + '"]').click();
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${screen} overflows at ${width}`);
    }
  }
  assert.deepEqual(errors, []);
  console.log('Preview checks passed: bottom dock stays fixed during active-sheet scroll; inspector tabs/pins; desktop Play fits without page scroll; typing never saves on a timer; Enter/blur commit; invalid HP preserves valid value; failure/retry; manager filtering; theme/density; 11 Home tools; separate public preview; no horizontal overflow at 320/736/1024/1920; no page errors. Local mock checks only.');
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
